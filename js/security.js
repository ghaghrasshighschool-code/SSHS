// Security Utility Module for SS+2 High School Ghaghra Notes Portal
// Enforces Zero-Risk Security Policies: XSS Prevention, Safe URLs, Input Sanitization, PDF Magic Byte Verification

const Security = {
  // 1. Robust HTML Entity Sanitization (Prevents DOM XSS)
  escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;')
      .replace(/`/g, '&#96;')
      .replace(/\//g, '&#x2F;');
  },

  // 2. Strict URL Protocol Sanitizer (Prevents javascript:, data:text/html, and open redirects)
  sanitizeUrl(rawUrl) {
    if (!rawUrl || typeof rawUrl !== 'string') return 'about:blank';
    const trimmed = rawUrl.trim();

    // Allow safe relative paths
    if (trimmed.startsWith('./') || trimmed.startsWith('/') || trimmed.startsWith('notes/')) {
      // Disallow path traversal attacks
      if (trimmed.includes('../') || trimmed.includes('..\\')) {
        console.warn('[Security] Path traversal attempt blocked:', rawUrl);
        return 'about:blank';
      }
      return encodeURI(trimmed);
    }

    // Allow blob URLs generated by browser for local offline PDFs
    if (trimmed.startsWith('blob:')) {
      return trimmed;
    }

    // For absolute URLs, strictly enforce http: and https: protocols only
    try {
      const parsed = new URL(trimmed, window.location.origin);
      if (parsed.protocol === 'http:' || parsed.protocol === 'https:') {
        return parsed.href;
      }
    } catch (e) {
      console.warn('[Security] Invalid URL format rejected:', rawUrl);
    }

    console.warn('[Security] Dangerous or unauthorized URL protocol blocked:', rawUrl);
    return 'about:blank';
  },

  // 3. Strict Filename Sanitizer (Prevents Directory Traversal & Shell Metacharacters)
  sanitizeFilename(name) {
    if (!name || typeof name !== 'string') return 'document.pdf';
    // Remove all directory separators and keep only safe characters
    let clean = name.replace(/^.*[\\\/]/, ''); // Strip paths
    clean = clean.replace(/[^a-zA-Z0-9_\-\.]/g, '_'); // Safe chars
    if (!clean.toLowerCase().endsWith('.pdf')) {
      clean += '.pdf';
    }
    return clean;
  },

  // 4. PDF Magic Byte Verification (Validates real PDF signature: %PDF)
  async verifyPdfMagicBytes(file) {
    if (!file || !(file instanceof Blob)) return false;
    try {
      const slice = file.slice(0, 5);
      const buffer = await slice.arrayBuffer();
      const bytes = new Uint8Array(buffer);
      // Expected ASCII for '%PDF-' is [0x25, 0x50, 0x44, 0x46, 0x2D]
      const magic = String.fromCharCode(...bytes);
      return magic.startsWith('%PDF');
    } catch (err) {
      console.error('[Security] Failed to inspect file signature:', err);
      return false;
    }
  },

  // 5. Cryptographic SHA-256 Hashing for Admin PIN (Never store or compare plaintext PIN)
  async hashString(value) {
    if (!window.crypto || !window.crypto.subtle) {
      // Fallback simple hash if Web Crypto unavailable
      let hash = 0;
      for (let i = 0; i < value.length; i++) {
        hash = ((hash << 5) - hash) + value.charCodeAt(i);
        hash |= 0;
      }
      return 'hash_' + Math.abs(hash).toString(16);
    }
    const encoder = new TextEncoder();
    const data = encoder.encode(value);
    const hashBuffer = await window.crypto.subtle.digest('SHA-256', data);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
  },

  // 6. Anti-Brute-Force Rate Limiter for Login
  isRateLimited(key = 'admin_login', maxAttempts = 5, lockTimeSeconds = 60) {
    const storageKey = `sec_rl_${key}`;
    try {
      const record = JSON.parse(localStorage.getItem(storageKey) || '{}');
      const now = Date.now();
      if (record.lockedUntil && now < record.lockedUntil) {
        const remaining = Math.ceil((record.lockedUntil - now) / 1000);
        return { limited: true, remainingSeconds: remaining };
      }
      return { limited: false, attempts: record.attempts || 0 };
    } catch (e) {
      return { limited: false, attempts: 0 };
    }
  },

  recordFailedAttempt(key = 'admin_login', maxAttempts = 5, lockTimeSeconds = 60) {
    const storageKey = `sec_rl_${key}`;
    try {
      const record = JSON.parse(localStorage.getItem(storageKey) || '{}');
      const now = Date.now();
      const attempts = (record.attempts || 0) + 1;
      let lockedUntil = null;
      if (attempts >= maxAttempts) {
        lockedUntil = now + (lockTimeSeconds * 1000);
      }
      localStorage.setItem(storageKey, JSON.stringify({ attempts: attempts, lockedUntil: lockedUntil }));
      return { attempts: attempts, locked: !!lockedUntil };
    } catch (e) {
      return { attempts: 1, locked: false };
    }
  },

  resetRateLimit(key = 'admin_login') {
    try {
      localStorage.removeItem(`sec_rl_${key}`);
    } catch (e) {}
  }
};

// Global Exposure
if (typeof window !== 'undefined') {
  window.Security = Security;
}
if (typeof module !== 'undefined') {
  module.exports = Security;
}
