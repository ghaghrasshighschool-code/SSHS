// Security Utility Module for SS+2 High School Ghaghra Notes Portal
// Enforces Zero-Risk Security Policies: XSS Prevention, Safe URLs, Input Sanitization, PDF Magic Byte Verification

const Security = {
  // 1. Robust HTML Entity Sanitization (Prevents DOM XSS)
  escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;')
      .replace(/`/g, '&#96;')
      .replace(/\//g, '&#x2F;');
  },

  // 2. Strict URL Protocol Sanitizer (Prevents javascript:, data:text/html, and open redirects)
  sanitizeUrl(rawUrl) {
    if (!rawUrl || typeof rawUrl !== 'string') return 'about:blank';
    const trimmed = rawUrl.trim();

    // Allow safe relative paths
    if (trimmed.startsWith('./') || trimmed.startsWith('/') || trimmed.startsWith('notes/')) {
      // Disallow path traversal attacks
      if (trimmed.includes('../') || trimmed.includes('..\\')) {
        console.warn('[Security] Path traversal attempt blocked:', rawUrl);
        return 'about:blank';
      }
      return encodeURI(trimmed);
    }

    // Allow blob URLs generated by browser for local offline PDFs
    if (trimmed.startsWith('blob:')) {
      return trimmed;
    }

    // For absolute URLs, strictly enforce http: and https: protocols only
    try {
      const parsed = new URL(trimmed, window.location.origin);
      if (parsed.protocol === 'http:' || parsed.protocol === 'https:') {
        return parsed.href;
      }
    } catch (e) {
      console.warn('[Security] Invalid URL format rejected:', rawUrl);
    }

    console.warn('[Security] Dangerous or unauthorized URL protocol blocked:', rawUrl);
    return 'about:blank';
  },

  // 3. Strict Filename Sanitizer (Prevents Directory Traversal & Shell Metacharacters)
  sanitizeFilename(name) {
    if (!name || typeof name !== 'string') return 'document.pdf';
    // Remove all directory separators and keep only safe characters
    let clean = name.replace(/^.*[\\\/]/, ''); // Strip paths
    clean = clean.replace(/[^a-zA-Z0-9_\-\.]/g, '_'); // Safe chars
    if (!clean.toLowerCase().endsWith('.pdf')) {
      clean += '.pdf';
    }
    return clean;
  },

  // 4. PDF Magic Byte Verification (Validates real PDF signature: %PDF)
  async verifyPdfMagicBytes(file) {
    if (!file || !(file instanceof Blob)) return false;
    try {
      const slice = file.slice(0, 5);
      const buffer = await slice.arrayBuffer();
      const bytes = new Uint8Array(buffer);
      // Expected ASCII for '%PDF-' is [0x25, 0x50, 0x44, 0x46, 0x2D]
      const magic = String.fromCharCode(...bytes);
      return magic.startsWith('%PDF');
    } catch (err) {
      console.error('[Security] Failed to inspect file signature:', err);
      return false;
    }
  },

  // 5. Cryptographic SHA-256 Hashing for Admin PIN (Never store or compare plaintext PIN)
  async hashString(value) {
    if (!window.crypto || !window.crypto.subtle) {
      // Fallback simple hash if Web Crypto unavailable
      let hash = 0;
      for (let i = 0; i < value.length; i++) {
        hash = ((hash << 5) - hash) + value.charCodeAt(i);
        hash |= 0;
      }
      return 'hash_' + Math.abs(hash).toString(16);
    }
    const encoder = new TextEncoder();
    const data = encoder.encode(value);
    const hashBuffer = await window.crypto.subtle.digest('SHA-256', data);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
  },

  // 6. Anti-Brute-Force Rate Limiter for Login
  isRateLimited(key = 'admin_login', maxAttempts = 5, lockTimeSeconds = 60) {
    const storageKey = `sec_rl_${key}`;
    try {
      const record = JSON.parse(localStorage.getItem(storageKey) || '{}');
      const now = Date.now();
      if (record.lockedUntil && now < record.lockedUntil) {
        const remaining = Math.ceil((record.lockedUntil - now) / 1000);
        return { limited: true, remainingSeconds: remaining };
      }
      return { limited: false, attempts: record.attempts || 0 };
    } catch (e) {
      return { limited: false, attempts: 0 };
    }
  },

  recordFailedAttempt(key = 'admin_login', maxAttempts = 5, lockTimeSeconds = 60) {
    const storageKey = `sec_rl_${key}`;
    try {
      const record = JSON.parse(localStorage.getItem(storageKey) || '{}');
      const now = Date.now();
      const attempts = (record.attempts || 0) + 1;
      let lockedUntil = null;
      if (attempts >= maxAttempts) {
        lockedUntil = now + (lockTimeSeconds * 1000);
      }
      localStorage.setItem(storageKey, JSON.stringify({ attempts: attempts, lockedUntil: lockedUntil }));
      return { attempts: attempts, locked: !!lockedUntil };
    } catch (e) {
      return { attempts: 1, locked: false };
    }
  },

  resetRateLimit(key = 'admin_login') {
    try {
      localStorage.removeItem(`sec_rl_${key}`);
    } catch (e) {}
  },

  // 7. Smart Automatic File Classification for IT/ITeS (Class 9-12 & Subject Sections)
  // Supports both Filename and Google Drive Folder Context (DDEO, JSD, QUESTIONS, BOOKS, HTML NOTES, ExtraS, COMMON)
  autoCategorize(filename, folderContext = '') {
    if (!filename || typeof filename !== 'string') {
      return { classKey: '9th', categoryId: 'part-b', categoryName: '💻 Part B: IT Specific Skills', cleanTitle: 'IT Study Notes', isSyllabus: false };
    }
    const name = filename.replace(/\.pdf$/i, '').trim();
    const fContext = (typeof folderContext === 'string' ? folderContext : '').toLowerCase();
    const s = (fContext + ' ' + name).toLowerCase();

    // 1. Detect Class (12, 11, 10, then 9)
    let classKey = '9th';
    if (/(?:class|cl|std|grade)?[ _-]*12(?:th)?(?=[^0-9]|$)|(?:\b|_)xii(?=[^a-z]|$)/i.test(s)) {
      classKey = '12th';
    } else if (/(?:class|cl|std|grade)?[ _-]*11(?:th)?(?=[^0-9]|$)|(?:\b|_)xi(?=[^a-z]|$)/i.test(s)) {
      classKey = '11th';
    } else if (/(?:class|cl|std|grade)?[ _-]*10(?:th)?(?=[^0-9]|$)|(?:\b|_)x(?=[^a-z0-9]|$)/i.test(s)) {
      classKey = '10th';
    } else if (/(?:class|cl|std|grade)?[ _-]*9(?:th)?(?=[^0-9]|$)|(?:\b|_)ix(?=[^a-z]|$)/i.test(s)) {
      classKey = '9th';
    } else if (s.includes('jsd')) {
      // Junior Software Developer (JSD - Code 802) is senior secondary (Classes 11 & 12)
      classKey = '11th';
    } else if (s.includes('ddeo')) {
      // Domestic Data Entry Operator (DDEO - Code 402) is secondary (Classes 9 & 10)
      classKey = '10th';
    }

    // 2. Detect Section / Category
    let categoryId = 'part-b';
    let categoryName = '💻 Part B: IT Specific Skills';
    let isSyllabus = false;

    if (/syllabus|curriculum|scheme|course|blueprint/i.test(s)) {
      categoryId = 'syllabus';
      categoryName = '📋 Syllabus (पाठ्यक्रम)';
      isSyllabus = true;
    } else if (/question|sample|model|paper|pyq|test|blueprint/i.test(s)) {
      // Questions / Model Question Papers
      categoryId = 'sample-papers';
      categoryName = '📝 Model Papers & Blueprint';
    } else if (/part[ _-]?a|employability|communication|self|green|entrepreneur/i.test(s)) {
      categoryId = 'part-a';
      categoryName = '📖 Part A: Employability Skills';
    } else if (/practical|lab|manual|viva|project|extras/i.test(s)) {
      categoryId = 'practical';
      categoryName = '🔬 Practical & Lab Manual';
    } else if (/html|book|textbook|ddeo|jsd/i.test(s)) {
      categoryId = 'part-b';
      categoryName = '💻 Part B: IT Specific Skills';
    }

    // 3. Format Clean Title
    let clean = name
      .replace(/(?:class|cl|std|grade)?[ _-]*(?:9|10|11|12)(?:th)?/gi, '')
      .replace(/\b(?:9th|10th|11th|12th)\b/gi, '')
      .replace(/\b(?:ix|x|xi|xii)\b/gi, '')
      .replace(/\b(?:it|ites|it-ites)\b/gi, '')
      .replace(/[-_]+/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();

    // Check if filename had very little info, enrich it from folder context
    if (!clean || clean.length < 3) {
      if (s.includes('html')) {
        clean = `Class ${classKey} HTML & Web Applications Notes`;
      } else if (s.includes('ddeo')) {
        clean = `Class ${classKey} DDEO Vocational Study Material`;
      } else if (s.includes('jsd')) {
        clean = `Class ${classKey} JSD Vocational Study Material`;
      } else {
        clean = `Class ${classKey} IT/ITeS Study Notes`;
      }
    } else if (isSyllabus) {
      clean = `Class ${classKey} IT/ITeS Official Syllabus (2025-26)`;
    } else {
      clean = clean.split(' ').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
    }

    const isCommon = Boolean(s.includes('common') || s.includes('all classes'));

    // 4. Detect Folder Header (DDEO, JSD, BOOKS, HTML_NOTES, EXTRAS, ALL_CLASSES)
    let folderHeader = 'DDEO';
    let subFolder = 'all';

    // Prioritize explicit folder context from Google Drive hierarchy
    const fc = folderContext.toLowerCase();
    if (fc.includes('all classes') || fc.includes('all_classes')) {
      folderHeader = 'ALL_CLASSES';
    } else if (fc.includes('extras') || fc.includes('extra')) {
      folderHeader = 'EXTRAS';
    } else if (fc.includes('html notes') || fc.includes('html_notes')) {
      folderHeader = 'HTML_NOTES';
    } else if (fc.includes('books') || fc.includes('book')) {
      folderHeader = 'BOOKS';
    } else if (fc.includes('jsd')) {
      folderHeader = 'JSD';
    } else if (fc.includes('ddeo')) {
      folderHeader = 'DDEO';
    } else if (s.includes('jsd')) {
      folderHeader = 'JSD';
    } else if (s.includes('ddeo')) {
      folderHeader = 'DDEO';
    } else if (s.includes('html')) {
      folderHeader = 'HTML_NOTES';
    } else if (s.includes('book') || s.includes('textbook') || s.includes('ncert')) {
      folderHeader = 'BOOKS';
    } else if (s.includes('extra') || s.includes('practical') || /\blabs?\b/i.test(s) || s.includes('project')) {
      folderHeader = 'EXTRAS';
    } else if (s.includes('all class') || s.includes('all_class') || isCommon) {
      folderHeader = 'ALL_CLASSES';
    } else if (classKey === '11th' || classKey === '12th') {
      folderHeader = 'JSD';
    } else {
      folderHeader = 'DDEO';
    }

    // Detect Subfolder inside Folder
    if (s.includes('class 9') || s.includes('class9') || s.includes('9th') || s.includes('/ 9 /')) {
      subFolder = 'class9';
    } else if (s.includes('class 10') || s.includes('class10') || s.includes('10th') || s.includes('/ 10 /')) {
      subFolder = 'class10';
    } else if (s.includes('class 11') || s.includes('class11') || s.includes('11th') || s.includes('/ 11 /')) {
      subFolder = 'class11';
    } else if (s.includes('class 12') || s.includes('class12') || s.includes('12th') || s.includes('/ 12 /')) {
      subFolder = 'class12';
    } else if (s.includes('common')) {
      subFolder = 'common';
    } else if (s.includes('question') || s.includes('sample') || s.includes('model') || s.includes('pyq')) {
      subFolder = 'questions';
    }

    return { classKey, categoryId, categoryName, cleanTitle: clean, isSyllabus, isCommon, folderHeader, subFolder };
  }
};

// Global Exposure
if (typeof window !== 'undefined') {
  window.Security = Security;
}
if (typeof module !== 'undefined') {
  module.exports = Security;
}
